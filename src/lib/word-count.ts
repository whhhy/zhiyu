/* ============================================================
   一篇文档的字数 —— 服务端与前端**共用**同一套口径
   ------------------------------------------------------------
   为什么要有这个文件：2026-10-06 之前，这件事在两个地方各写了一遍，
   而且**两个都不对，但错的方向相反**：

     · 前端 store/index.ts   blocks 的 text.length 求和
       → 保留空白（英文句子里的空格全算进字数）
       → 不含 markdown 符号（好）
     · 服务端 index.ts       markdown 去掉空白后的长度
       → 去掉了空白（好）
       → 但把 `# - [ ] * | >` 这些**标记符号也当成字**了（`# 标题` 算 3 个字）

   实测一篇 11 块的文档：前端 140 / 服务端 131，**差 9 字**。
   而 `doc.wordCount` 是要给人看的 —— 文档头、知识库列表、工作台统计、
   发现页、目录树都显示它。同一个数字会因为文档走 API 还是走编辑器而变。

   两边注释里写的**意图**其实一致：「去空白后按字符数」。
   错的只是各自选了不同的输入。所以这里把它收在一处，
   两边都调它 —— 跟 body / title 的做法一样：一个派生值只有一处能写对。
   ============================================================ */

export interface CountableBlock {
  text?: unknown
}

/**
 * 一组块的中文字数：逐块取 text，去掉所有空白后按字符数累加。
 *
 * 为什么去掉空白：中文正文里本来就没有空格，留着它只会让
 * 「同一段英文」在两个口径下算出两个数。
 * 为什么不用 markdown 算：`# ` 是 2 个字符、`- [ ] ` 是 6 个字符、
 * 表格的 `| --- |` 更是一堆 —— 用户没写这些，计数里也不该有。
 */
export function countWordsFromBlocks(blocks: unknown): number {
  if (!Array.isArray(blocks)) return 0
  let n = 0
  for (const b of blocks as CountableBlock[]) {
    if (!b || typeof b !== 'object') continue
    if (typeof b.text === 'string') n += b.text.replace(/\s+/g, '').length
  }
  return n
}