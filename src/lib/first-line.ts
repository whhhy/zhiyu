/* ============================================================
   「第一行有内容的源码」—— 各图种判定的共同入口
   ------------------------------------------------------------
   ⚠️ 为什么值得单独一个文件：这个判据在 7 个模块里各写了一遍
      （statediagram / pie / timeline / er / class / mindmap / journey），
      而**每一份都带着同一个缺陷**：跳过 `%%` 注释与空行之后拿到的是
      **带缩进**的那一行，却拿它去 `/^journey\b/i` 这种**行首**正则上测 ——
      于是「前面有空行或注释、且图种头有缩进」的正常写法被判成「不是这个图种」。

   症状形态：不报错、不空图，只是路由落到兜底分支，
   界面上给出一张**不相干**的结构预览（用户只会以为自己的源码写错了）。

   另一个坑是**别用整段 `.trim()` 之后再 split**：那样只有第一行去掉了缩进，
   后面几行照旧带缩进 —— 恰恰是这个 bug 的成因。

   少写一张映射表？那张表自己就会开始漂 —— 这条和 diagram.ts 里
   「路由判定只留一份」是同一个道理。
   ============================================================ */

/** 第一行**有内容且不是 `%%` 注释**的**那一行（已 trim）。没有则返回空串。 */
export function firstMeaningfulLine(src: string): string {
  for (const raw of String(src || '').split('\n')) {
    const t = raw.trim()
    if (!t || t.startsWith('%%')) continue
    return t
  }
  return ''
}
