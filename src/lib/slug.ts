/* ============================================================
   文档「路径」（slug）的归一化
   ------------------------------------------------------------
   刻意做成纯函数、不依赖任何东西：**服务端和前端都要用同一份**。

   理由很实际：归一化规则一旦有两份实现，用户在 A 处看到的地址
   和 B 处存下来的地址就会不一样 —— 表现为「我明明填的是小写，
   分享出去的链接却 404」。这种错极难查，因为两边各自都对。
   （markdownToBlocks 当初也是同一个理由抽出去的。）
   */

/**
 * 统一成小写、连字符分隔、只留字母数字和连字符。
 *
 * 几条细则都是有原因的：
 *   · 先折空白再换成连字符：否则 `a  b`（两个空格）会变成 `a--b`
 *   · 非字母数字先换成连字符再折叠：`a.b` 与 `a b` 归到同一个地址
 *   · 掐掉首尾的连字符：`-abc-` 应该是 `abc`
 *   · 限长 80：路径不是正文，写太长既难看也更容易撞名
 *
 * **中文标题会归一化成空串**，这是如实的结果而不是失败：
 * 没有路径就退回用 docId，而不是编一个拼音出来 ——
 * 编出来的东西看起来像真的，点开却是另一篇，比空着更糟。
 */
export const normalizeSlug = (raw: unknown): string => {
  let s = String(raw ?? '').trim().toLowerCase()
  s = s.replace(/\s+/g, '-')
  s = s.replace(/[^a-z0-9-]+/g, '-')
  s = s.replace(/-{2,}/g, '-')
  s = s.replace(/^-+|-+$/g, '')
  return s.slice(0, 80)
}

/**
 * 一个文档对外的地址。
 *
 * 有路径用路径，没有退回 docId —— 两种都是**能打开的**地址。
 * 以前这里写死的是 `https://www.yuque.com/yuque-clone/<id>`：
 * 复制成功、toast 成功、点得开，指向语雀官网上一个不存在的路径。
 */
export const docShareUrl = (origin: string, docId: string, slug?: string): string =>
  `${origin}/#/public/doc/${normalizeSlug(slug) || docId}`
