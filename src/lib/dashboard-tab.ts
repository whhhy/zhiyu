/*
 * 协作 tab 从「隐藏」改成「正常显示」—— 因为它现在是**真的**了。
 *
 * ⚠️⚠️ 这份文件里曾经有一处「因为是假数据所以在服务端形态下隐藏它」，
 *    连注释都写得很确信（「服务端永远 []，那页恒空且带两个假按钮」）。
 *    2026-10-11 补了真正的知识库邀请之后，那条前提**不成立了** ——
 *    继续按旧口径隐藏，就等于把已经能用的功能继续藏着。
 *
 *    而这类「过期的口径」比没有更糟：它看起来像一条有意的产品决策，
 *    下一个人读到注释会以为「这是我们特意做的」，于是不去查。
 *
 *    所以这里改成：**协作 tab 始终可见**。
 *    本地模式下点进去会看到「邀请需要连着服务端才能用」的明确说明
 *    （不是恒空列表 + 假按钮），服务端模式下是真待办。
 */
import { getMode } from './api'

/**
 * 把 URL 上的 `tab` 参数解析成真正该渲染 / 该高亮的 tab。
 *
 * ⚠️ 高亮与渲染必须走同一份口径 —— SideNav 和 Dashboard 都调它。
 *    两处各算各的就会出现「内容对了、导航错了」的半截状态
 *    （侧栏一个高亮都没有，看起来像「点哪儿都没反应」）。
 *
 *    现在没有需要改写的 tab 了，但 `resolveTab` 仍留着：
 *    它是这个「口径只有一份」的**机制**，删了就等于回到两处各算各的状态。
 */
export function resolveTab(raw: string | null | undefined): string {
  return raw || 'doc'
}

/**
 * 这一项在当前形态下是否应该出现在侧栏。
 *
 * 现在**恒为 true**。原因写清楚，免得下一个人看到「一个没有分支的函数」
 * 就顺手删掉它 —— 那个字段还记着当初为什么会漏掉 SideNav 那一半。
 */
export function tabVisible(_key: string): boolean {
  return true
}

/** 当前形态下协作 tab 是不是「只有说明、没有内容」的那种（用于副标题） */
export function collabIsLocalOnly(): boolean {
  return getMode() !== 'server'
}
